#!/usr/bin/env node
/**
 * Auto-generates src/lib/exerciseImages.ts from exercise-image-manifest.json.
 *
 * Usage: node scripts/generate-exercise-images-ts.mjs
 */

import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const ROOT = path.resolve(__dirname, '..');
const MANIFEST = path.join(ROOT, 'scripts/output/exercise-image-manifest.json');
const OUT = path.join(ROOT, 'src/lib/exerciseImages.ts');
const ASSETS = path.join(ROOT, 'assets/exercises');

function quoteKey(name) {
  if (/^[A-Za-z_][A-Za-z0-9_]*$/.test(name)) return name;
  if (name.includes("'")) return `'${name.replace(/'/g, "\\'")}'`;
  return `'${name}'`;
}

function main() {
  const manifest = JSON.parse(fs.readFileSync(MANIFEST, 'utf8'));
  const existingSlugs = new Set(
    fs.readdirSync(ASSETS).filter((f) => f.endsWith('.jpg')).map((f) => f.replace(/\.jpg$/, '')),
  );

  const sorted = [...manifest].sort((a, b) => a.name.localeCompare(b.name));
  const lines = sorted.map((entry) => {
    if (!existingSlugs.has(entry.slug)) {
      console.warn(`Missing image: ${entry.slug}.jpg (${entry.name})`);
    }
    return `  ${quoteKey(entry.name)}: require('../../assets/exercises/${entry.slug}.jpg'),`;
  });

  const content = `import type { ImageSourcePropType } from 'react-native';

// React Native requires static require() calls, so images are mapped explicitly
// by master-exercise name rather than derived from slugs at runtime.
// Auto-generated by scripts/generate-exercise-images-ts.mjs — do not edit by hand.
const EXERCISE_IMAGES: Record<string, ImageSourcePropType> = {
${lines.join('\n')}
};

/**
 * Returns the bundled anatomical illustration for a master exercise,
 * or null for exercises without one (e.g. user custom exercises).
 */
export function getExerciseImage(exerciseName: string): ImageSourcePropType | null {
  return EXERCISE_IMAGES[exerciseName] ?? null;
}
`;

  fs.writeFileSync(OUT, content);
  console.log(`Wrote ${OUT} with ${sorted.length} entries (${existingSlugs.size} JPGs on disk).`);
}

main();
